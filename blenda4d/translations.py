def register():
    t = bpy.app.translations
    entries = {}
    for msgid, msgstr in STRINGS.items():
        for ctx in _CONTEXTS:
            # only where Blender's own dictionary has nothing: its bilingual entries always win
            if t.pgettext(msgid, ctx) == msgid:
                entries[(ctx, msgid)] = msgstr
    if entries:
        t.register(__package__, {"zh_HANS": entries})


def unregister():
    bpy.app.translations.unregister(__package__)


